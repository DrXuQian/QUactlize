ROOT = Path(__file__).resolve().parents[2]
CONTROLS = Path(__file__).with_name('model_controls.json')


def model_points(header):
    if header['metadata'].get('general.architecture') != 'qwen3':
        raise ValueError('this diagnostic is Qwen3-32B, not a model-zoo sweep')
    groups, omitted, layers, matrices = {}, [], set(), set()
    for t in header['tensors']:
        if len(t['dims_gguf']) != 2: continue
        match = re.fullmatch(r'blk\.(\d+)\.(attn_[qkv]|attn_output|ffn_gate|ffn_up|ffn_down)\.weight', t['name'])
        if not match:
            if t['name'] not in ('token_embd.weight', 'output.weight'):
                raise ValueError('unreviewed model matrix: '+t['name'])
            omitted.append(dict(tensor=t['name'], reason='LOOKUP_OR_M1_OUTPUT_HEAD'))
            continue
        layer, projection = int(match[1]), match[2]
        if t['name'] in matrices: raise ValueError('duplicate model matrix')
        matrices.add(t['name'])
        layers.add(layer)
        if layer == 63 and projection.startswith('ffn_'):
            omitted.append(dict(tensor=t['name'], reason='LAST_LAYER_SELECTED_TOKEN_M1_IN_REVIEWED_PP_TRACE'))
            continue
        k, n = t['dims_gguf']
        w = Workload(t['qtype'], n, k, 2048)
        groups.setdefault(w.key, dict(id=w.key, workload=asdict(w), tensors=[]))['tensors'].append(t['name'])
    expected = json.loads(CONTROLS.read_text())['points']
    if (len(matrices) != 448 or layers != set(range(64)) or set(groups) != {Workload(**p['workload']).key for p in expected}
            or sum(len(p['tensors']) for p in groups.values()) != 445):
        raise ValueError('GGUF does not match the reviewed seven-family / 445-call PP2048 inventory')
    return groups, omitted


def freeze(header, output):
    groups, omitted = model_points(header)
    prior = make_plan('prefill')
    points = [p for p in prior['points'] if p['id'] in groups]
    if {p['id'] for p in points} != set(groups): raise ValueError('missing model family in candidate rules')
    bind_original(points, output)
    controls = {Workload(**p['workload']).key:p['recipe'] for p in json.loads(CONTROLS.read_text())['points']}
    for p in points:
        p.update(groups[p['id']])
        p['model_config_control'] = controls[p['id']]
        # Separate controls preserve the installed-model config AND current
        # source selection, without pretending they were generated by rules.
        p['champion_controls'].append(controls[p['id']])
        w = Workload(**p['workload'])
        cp = dict(Recipe.from_dict(controls[p['id']]).parameters)
        p['sf_config'] = cp.get('dequant_config', 4 if w.qtype == 12 else 0)
        if Recipe.from_dict(controls[p['id']]).route != 'sf':
            p['sf_config'] = 4 if w.qtype == 12 else 0
        p['full_configs'] = list(expansion_configs(w, 'full'))
    result = dict(schema='quactlize.model-prefill-asys.v1', model='Qwen3-32B-Q4_K_M', m=2048,
        points=points, omitted=omitted, model_control_sha256=sha(CONTROLS),
        measurement='ASYS_GPU_ACTIVITIES_INSIDE_COMPLETE_ROTATING_CALLS',
        arithmetic='EXTERNAL_F32; NATIVE_AND_TC_F16; SEPARATE_FULL_F16_AND_BF16; ALL_ACCUMULATORS_F32',
        helper_policy='PRODUCTION_ZW810_PP2048_R4; RETAIN_LEGACY_CONTROLS',
        sf_expansion='FIXED_MODEL_CONTROL_OR_Q4_CONFIG4_Q6_CONFIG0; NOT_A_HELPER_CONFIG_SWEEP',
        candidates='ALL_LEGAL_RULE_AND_CONTROL_RECIPES; DISTINCT_RESOURCE_RESOLVED_GRIDS',
        scope='SEVEN_QUANTIZED_DENSE_FAMILIES_NOT_ALL_LEGAL_CARTESIAN_CONFIGS_NOT_MODEL_E2E',
        kernel_changes=False, production_changed=False, performance_admitted=False)
    result['counts'] = dict(points=len(points), pp_calls=445, **inventory(result)['counts'],
                            recipes_before_grid_resolution=sum(len(p['candidates']) for p in points))
    result['plan_sha256'] = digest(result)
    return json.loads(json.dumps(result))


def runnable(point):
    """Only launch aliases are deduplicated; reducers stay in each full call."""
    pool = {}
    values = [('rule', r) for r in point['candidates']]
    values += [('control', r) for r in point['champion_controls']]
    if point.get('original_recipe'): values.append(('source-current', point['original_recipe']))
    values.append(('model-config', point['model_config_control']))
    w = Workload(**point['workload'])
    from dev.strategy.space import resolved_grid
    from dev.strategy.resources import module_spec, probe_spec
    for role, value in values:
        r = Recipe.from_dict(value)
        if r.kind == 'full': continue
        p = dict(r.parameters)
        if r.route == 'sf': p['dequant_config'] = point['sf_config']
        r = Recipe.make(r.kind, r.route, **p)
        spec = module_spec(w, r)
        query = digest(probe_spec(w, r, int(p.get('grid_mode', 0) >= 2)))
        receipt = point['queries'][query]
        if receipt['status'] != 'READY':
            raise ValueError('required launch unavailable: '+r.key)
        launch = resolved_grid(w, r, receipt['device']['compute_units'], receipt['occupancy'])
        key = digest([spec, launch, p.get('dequant_config', -1)])
        row = pool.setdefault(key, dict(id=key, arm=r.route, recipe=asdict(r),helper_mode='production',
            module=digest(spec), launch=launch, roles=[]))
        if role not in row['roles']: row['roles'].append(role)
    # Only the model/current config gets an old-helper twin. The TC search
    # is not doubled, nor does the new route replace its control's evidence.
    for row in list(pool.values()):
        controls=[r for r in row['roles'] if r in ('model-config','source-current')]
        if controls:
            key=digest([row['id'],'legacy-helpers'])
            pool[key]=dict(row,id=key,helper_mode='legacy',roles=['legacy-'+r for r in controls])
    # Full-dequant+cuBLAS is part of the search, not a separately omitted
    # fallback. Direct BF16 expansion, no F16->BF16 relabelling.
    for c in point['full_configs']:
        r = Recipe.make('full','full',dequant_config=c,provider='bf16-default')
        row = dict(id=r.key, arm='full-bf16', recipe=asdict(r),helper_mode='legacy',roles=['legacy-full'])
        for role, value in values:
            other = Recipe.from_dict(value)
            if other.kind == 'full' and dict(other.parameters).get('dequant_config') == c:
                legacy_role='legacy-'+role
                if legacy_role not in row['roles']: row['roles'].append(legacy_role)
        pool[row['id']] = row
    for storage,arm in ((0,'full-fp16'),(1,'full-bf16-typed')):
        # Query the SAME compiled helper policy as the production facade on
        # device; do not copy its table or stale timings into this Python plan.
        r=Recipe.make('full','full',provider='typed-fp16' if not storage else 'typed-bf16',
                      helper_policy='production-r4')
        roles=['typed-full','same-dtype-native' if not storage else 'bf16-alternative']
        if storage:
            roles += sorted({role for role,value in values if Recipe.from_dict(value).kind=='full'})
        pool[r.key]=dict(id=r.key,arm=arm,recipe=asdict(r),helper_mode='production',roles=roles)
    # Config order is deterministic and independent of historical times.
    return sorted(pool.values(), key=lambda r:digest([point['id'],r['id']]))
