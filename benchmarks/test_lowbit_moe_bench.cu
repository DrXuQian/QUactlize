namespace {
// ONE scanner for the whole sharded executable. Reduce the flags inside each block so a large prefill D performs at
// most two global atomics per block rather than one per thread. Neither this launch nor its readback is timed.
__global__ void moe_output_witness_scan(half_t const* d, size_t count, unsigned int* witness) {
  size_t i = size_t(blockIdx.x) * blockDim.x + threadIdx.x;
  size_t const stride = size_t(gridDim.x) * blockDim.x;
  unsigned int flags = 0;
  for (; i < count; i += stride) {
    uint16_t const v = d[i].raw();
    flags |= (v == uint16_t(0x7f7f)) ? 1u : 0u;
    flags |= ((v & uint16_t(0x7fff)) != 0 && v != uint16_t(0x7f7f)) ? 2u : 0u;
  }
  __shared__ unsigned int block_flags[256];
  block_flags[threadIdx.x] = flags;
  __syncthreads();
  for (int step = 128; step > 0; step >>= 1) {
    if (threadIdx.x < step) block_flags[threadIdx.x] |= block_flags[threadIdx.x + step];
    __syncthreads();
  }
  if (threadIdx.x == 0) {
    if (block_flags[0] & 1u) atomicAdd(witness + 0, 1u);
    if (block_flags[0] & 2u) atomicAdd(witness + 1, 1u);
  }
}
}  // namespace

void moe_poison_output(const Band& bd) {
  CUTLASS_PPU_CHECK(hggcMemset(bd.dD, 0x7f, bd.d_elems * sizeof(half_t)));
}

MoeOutputWitness moe_output_witness(const Band& bd) {
  if (bd.d_elems == 0 || bd.d_output_witness == nullptr) return {false, false};
  CUTLASS_PPU_CHECK(hggcMemset(bd.d_output_witness, 0, 2 * sizeof(unsigned int)));
  int const blocks = int(std::min<size_t>(256, (bd.d_elems + 255) / 256));
  moe_output_witness_scan<<<blocks, 256>>>(bd.dD, bd.d_elems, bd.d_output_witness);
  CUTLASS_PPU_CHECK(hggcDeviceSynchronize());
  unsigned int h[2] = {0, 0};
  cutlass::device_memory::copy_to_host(h, bd.d_output_witness, 2);
  return {h[0] == 0, h[1] != 0};
}

int main(int argc, char** argv) {
  // FIRST, before any allocation: a device switch after the context exists is not a switch.
  bench_device::bind_from_env();
  Band bd{};
  bd.L    = argc > 1 ? atoi(argv[1]) : (MOE_TABLE_DECODE ? 256 : 64);
  bd.Rows = argc > 2 ? atoi(argv[2]) : (MOE_TABLE_DECODE ? 4 : 128);
  bd.N    = argc > 3 ? atoi(argv[3]) : (MOE_TABLE_DECODE ? 512 : 2048);
  bd.K    = argc > 4 ? atoi(argv[4]) : 2048;
  bd.gs   = argc > 5 ? atoi(argv[5]) : 32;
  // SKEWED IS THE DEFAULT. Uniform row counts are the case that teaches least: every expert has the same m-tile count,
  // so there is no masking, no load imbalance, and no tail -- i.e. none of what makes MoE different from a batched
  // GEMM. Real row counts come from a router. mode 0 (uniform) is kept only as a control, and mode 1 exists to be
  // pointed at: its counts are all multiples of TileM, so it never enters the masked path at all.
  bd.mode = argc > 6 ? atoi(argv[6]) : (MOE_TABLE_DECODE ? 4 : 2);
  bd.topk = argc > 7 ? atoi(argv[7]) : 8;
  bd.scale_k = moe_scale_groups(bd.K, bd.gs);

  // ROW-COUNT DISTRIBUTION. The first ragged generator was (Rows/2)*((e%4)+1) -- 64, 128, 192, 256. Every count a
  // multiple of 64, hence a multiple of every TileM being swept, hence **the masked path was never entered at all**.
  // That is the same mistake as a probe whose period aliases the displacement it is hunting, in different clothing: a
  // "ragged" model whose raggedness is invisible to the thing under test measures the uniform case twice.
  //
  // Real MoE row counts come from a router, so mode 2 gives: arbitrary counts (not multiples of anything), a heavy tail
  // (one expert several times the mean), and ZERO-ROW experts, which are common at small batch and are their own path --
  // filter_and_run has to skip them rather than launch an empty tile.
  bd.me.resize(bd.L); bd.offs.resize(bd.L);
  if (bd.mode == 4) {
    moe_router_fixture::Rows routed;
    char why[128] = "";
    if (!moe_router_fixture::route(bd.Rows, bd.topk, bd.L, routed, why, sizeof why)) {
      std::printf("mode 4 router fixture refused: %s\n", why);
      return 1;
    }
    bd.me = routed.per_expert;
  }
  int zeros = 0, mn = 1 << 30;
  bd.total = 0; bd.Mmax = 0; bd.active = 0;
  for (int e = 0; e < bd.L; ++e) {
    if (bd.mode == 0)      bd.me[e] = bd.Rows;
    else if (bd.mode == 1) bd.me[e] = (bd.Rows / 2) * ((e % 4) + 1);
    // mode 3 = DECODE at batch 1. `Rows` is reinterpreted as top-k: exactly `Rows` experts get ONE row and the rest get
    // zero. Passing L=topk with rows=1 instead would measure the same arithmetic under a DISHONEST launch -- the real
    // call has all L groups present with most of them empty, and skipping those is work the scheduler actually does.
    else if (bd.mode == 3) bd.me[e] = (e < bd.Rows) ? 1 : 0;
    else if (bd.mode == 2) {
      // skewed: ~12% of experts get nothing, one in eight gets a heavy share, the rest scatter around the mean
      const unsigned h = (unsigned)(e * 2654435761u) >> 13;
      if ((h % 8) == 0)      bd.me[e] = 0;
      else if ((h % 8) == 1) bd.me[e] = int(bd.Rows * 3 + (h % 37));                          // heavy tail
      else                   bd.me[e] = int(bd.Rows / 2 + (h % (unsigned)(bd.Rows + 1)));      // not a multiple of TM
    } else if (bd.mode != 4) {
      std::printf("unknown row-distribution mode %d (expected 0..4)\n", bd.mode);
      return 1;
    }
    if (bd.me[e] == 0) ++zeros; else ++bd.active;
    mn = std::min(mn, bd.me[e]);
    bd.offs[e] = bd.total; bd.total += bd.me[e]; bd.Mmax = std::max(bd.Mmax, bd.me[e]);
  }
  if (bd.Mmax == 0) { std::printf("all experts empty; nothing to measure\n"); return 1; }
  // THE BOUND IS CHECKED AGAINST THE ROUTER'S ACTUAL HISTOGRAM. In mode 4 `Rows` is a token count, not rows per
  // expert: T=4 routes to Mmax=3 today, while guessing from either T or top-k would reject a covered shape or admit an
  // uncovered one. Refuse before any large host/device allocation and before every pack or kernel launch.
  if (MOE_TABLE_M_MAX > 0 && bd.Mmax > MOE_TABLE_M_MAX) {
    std::printf("[lowbit-moe] refusing table_band=%s table_mmax=%d: actual routed Mmax=%d "
                "(L=%d input=%d topk=%d mode=%d)\n",
                MOE_TABLE_BAND_STR, MOE_TABLE_M_MAX, bd.Mmax, bd.L, bd.Rows, bd.topk, bd.mode);
    return 2;
  }
  const char* mname = bd.mode == 0 ? "uniform"
                    : bd.mode == 1 ? "ragged-coarse(multiples of TM: masked path NEVER entered)"
                    : bd.mode == 3 ? "DECODE batch=1 (top-k experts x 1 row, rest empty)"
                    : bd.mode == 4 ? moe_router_fixture::kName
                                   : "skewed(arbitrary counts + zero-row experts)";
  std::printf("[lowbit-moe] table_band=%s table_mmax=%d actual_mmax=%d  PPU_B_CHUNK=row-axis  "
              "hdr_rev=%d  MOE_TK=%d  quant=%s  L=%d input=%d topk=%d mode=%s N=%d K=%d gs=%d\n",
              MOE_TABLE_BAND_STR, MOE_TABLE_M_MAX, bd.Mmax,
              LOWBIT_MOE_BENCH_REV, MOE_TK, LOWBIT_QMODE_STR, bd.L, bd.Rows, bd.topk, mname,
              bd.N, bd.K, bd.gs);
  if (moe_verbose()) {
    std::printf("             total=%d Mmax=%d Mmin=%d zero-row experts=%d active=%d  PEAK=%.0f TFLOP/s\n",
                bd.total, bd.Mmax, mn, zeros, bd.active,
                bench_measure::kPeakFlopsPerSecond / 1e12);
    std::printf("             MFU is on the REAL rows (2*total*N*K), so wasting rows cannot buy MFU.\n");
    // A LOG THAT DOES NOT DESCRIBE ITS OWN RUN. MOE_ACU and MOE_ONLY are exported for an acu capture and then stay exported
    // in the shell, so the next plain run silently measures ONE COLD LAUNCH of ONE row and reports it as the winner. Keep
    // the explanation available without making it the default preamble; the verdict header still says NOT a ranking.
    if (moe_only())  std::printf("             MOE_ONLY='%s' -- every other row is SKIPPED\n", moe_only());
    if (moe_acu())   std::printf("             *** MOE_ACU=1: ONE COLD LAUNCH per row, no warmup. These are NOT timings. ***\n");
    if (moe_abcast()) std::printf("             *** MOE_ABCAST=1: A's m-stride is 0, so the TileM-1 padding rows read the\n"
                                 "                 expert's real row. Legal ONLY at Mmax==1 -- launch() refuses it above\n"
                                 "                 that, so rows would be EXCLUDED rather than measured. ***\n");
    // Keep coverage and compile granularity separate: batching several wrappers into one TU must not make a quietly
    // smaller sweep look intentional, and adding shapes must not hide the reason a build crossed another compile wave.
    std::printf("             linked against %d generated sweep shapes in %d translation units "
                "(illegal shapes print nothing)\n", MOE_UNIT_COUNT, MOE_TU_COUNT);
    std::printf("             PPU_B_CHUNK requests: bc0=%d unit(s), bc1=%d unit(s); tags show request->effective\n",
                moe_chunk_tally().requested_off, moe_chunk_tally().requested_on);
  }

  std::vector<half_t> hA((size_t)bd.total * bd.K), hSc((size_t)bd.L * bd.scale_k * bd.N),
                      hZr((size_t)bd.L * bd.scale_k * bd.N);
  for (size_t i = 0; i < hA.size(); ++i) hA[i] = half_t(0.01f);
  for (size_t i = 0; i < hSc.size(); ++i) { hSc[i] = half_t(0.0625f); hZr[i] = half_t(0.5f); }
  cutlass::DeviceAllocation<half_t> dA((size_t)bd.total * bd.K), dSc((size_t)bd.L * bd.scale_k * bd.N),
                                    dZr((size_t)bd.L * bd.scale_k * bd.N), dD((size_t)bd.total * bd.N);
  cutlass::DeviceAllocation<unsigned int> d_output_witness(2);
  dA.copy_from_host(hA.data()); dSc.copy_from_host(hSc.data()); dZr.copy_from_host(hZr.data());

  bd.rsh.resize(bd.L);
  std::vector<half_t*> pdh(bd.L); std::vector<DStride> sdh(bd.L); std::vector<int> gmh(bd.L);
  for (int e = 0; e < bd.L; ++e) {
    bd.rsh[e] = cute::make_shape(bd.me[e], bd.N, bd.K); pdh[e] = dD.get() + (size_t)bd.offs[e] * bd.N;
    sdh[e] = cutlass::make_cute_packed_stride(DStride{}, cute::make_shape(bd.me[e], bd.N, 1)); gmh[e] = bd.me[e];
  }
  cutlass::DeviceAllocation<GS> rdev(bd.L);       rdev.copy_from_host(bd.rsh.data());
  cutlass::DeviceAllocation<half_t*> pd(bd.L);    pd.copy_from_host(pdh.data());
  cutlass::DeviceAllocation<DStride> sd(bd.L);    sd.copy_from_host(sdh.data());
  cutlass::DeviceAllocation<int> gm(bd.L);        gm.copy_from_host(gmh.data());
  cutlass::DeviceAllocation<int> offdev(bd.L);    offdev.copy_from_host(bd.offs.data());
  const size_t wsb = (size_t)cutlass::ceil_div(bd.Mmax,16)*cutlass::ceil_div(bd.N,64)*(size_t)bd.L*64;
  cutlass::DeviceAllocation<char> ws(wsb);
  bd.dA = dA.get(); bd.dSc = dSc.get(); bd.dZr = dZr.get();
  bd.dD = dD.get(); bd.d_elems = (size_t)bd.total * bd.N; bd.d_output_witness = d_output_witness.get();
  bd.rdev = rdev.get(); bd.pd = pd.get(); bd.sd = sd.get(); bd.gm = gm.get(); bd.offdev = offdev.get();
  bd.ws = ws.get(); bd.wsb = wsb;

  // ONE BEST PER NUMERIC PRECISION, not per implementation family. "two-plane best" groups Q3/Q5/Q6 together and
  // "single-plane" groups i2/i4 -- a split by how the kernel is built, not by anything a caller picks, and it hid i4's
  // own best entirely once i2 started winning the shared slot.
  Best b[MOE_FMT_COUNT];
  for (int i = 0; i < MOE_FMT_COUNT; ++i) { b[i].tag[0] = '\0'; b[i].us = b[i].wall_us = 1e18; }

  // THE WHOLE LIST, REPEATED -- not each candidate repeated in place. See the comment on Best in
  // lowbit_moe_bench.hpp: drift is time-correlated, so interleaving is what keeps it from landing on one
  // candidate. MOE_REPS=1 is allowed and is explicitly not a ranking.
  const int reps = moe_acu() ? 1 : bench_measure::read_reps("MOE_REPS");
  (void)bench_floor::us();  // measure before the sweep even when its explanatory banner is hidden
  if (moe_verbose()) bench_floor::banner();
  if (moe_acu())
    std::printf("  [timing] MOE_ACU=1 bypasses device-event sampling: one cold host-wall launch, not a timing\n");
  else
    std::printf("  [timing] primary us = device-event kernel-span upper bound around gemm.run"
                " (includes launch/idle; not profiler kernel-only)\n"
                "           audit = instrumented host-wall over the same launches;"
                " per-launch spread=(max-min)/mean, warmup excluded\n");
  char build_identity[192];
  char const* timing_identity = moe_acu() ? "acu-cold-host-wall-v1" : "event-kernel-span-upper-v1";
  std::snprintf(build_identity, sizeof build_identity,
                "PPU_B_CHUNK=row-axis %s table-band=%s table-m-max=%d hdr-rev=%d timing=%s",
                LOWBIT_QMODE_STR, MOE_TABLE_BAND_STR, MOE_TABLE_M_MAX,
                LOWBIT_MOE_BENCH_REV, timing_identity);
  bench_samples::run_header(MOE_TABLE_BENCH_STR, build_identity, reps);
  for (int r = 0; r < reps; ++r) {
    moe_pass() = r;
    if (reps > 1) std::printf("\n  --- pass %d/%d ---\n", r + 1, reps);
    moe_run_all(bd, b);
  }
  bench_samples::flush();
  int ties[MOE_FMT_COUNT];
  for (int i = 0; i < MOE_FMT_COUNT; ++i) { ties[i] = settle(b[i]); b[i].reps_seen = reps; }

  // THE ROOFLINE, STATED. Arithmetic intensity against the machine's ridge point decides which roof applies, and saying it
  // outright stops `%HBM` from having to be argued about: at decode AI is ~3 FLOP/B against a ridge of PEAK/HBM = 181, so the
  // memory roof is the only one in play and the measured time can be compared to it directly.
  if (moe_verbose()) {
    const double fl   = 2.0 * double(bd.total) * double(bd.N) * double(bd.K);
    const double ridge = bench_measure::ridge_flops_per_byte();
    std::printf("\n  roofline: ridge = PEAK/HBM = %.0f FLOP/B. This shape has %.0f MFLOP over the compulsory traffic below,\n",
                ridge, fl / 1e6);
    std::printf("            so read HBM%%%% as \"%%%% of the memory roof\": 100%%%% means saturated, and the shortfall is\n");
    std::printf("            latency or transaction efficiency, not bandwidth. run=/kit= are the two TileK-controlled\n");
    std::printf("            candidates for it (AIU contiguous run in bytes; k-iteration count).\n");
  }
  std::printf("\n  ================= %s =================\n",
              moe_acu() ? "MOE_ACU=1: single cold launches, NOT a ranking"
                        : reps < 2 ? "MOE_REPS=1: ONE timing per candidate -- NOT a ranking"
                                   : "VERDICT: best config per format");
  if (reps > 1 && moe_verbose())
    std::printf("  %d passes, median event-span per candidate, band = [min,max] over passes. A candidate whose\n"
                "  band reaches into the leader's is reported as a TIE, not beaten. The old 13%% host-wall\n"
                "  cross-run spread is not reused as an event-span noise floor; each row prints its own 20-launch spread.\n",
                reps);
  int ord[MOE_FMT_COUNT];
  for (int i = 0; i < MOE_FMT_COUNT; ++i) ord[i] = i;
  for (int i = 1; i < MOE_FMT_COUNT; ++i)                    // insertion sort: 5 entries, fastest first
    for (int j = i; j > 0 && b[ord[j]].us < b[ord[j-1]].us; --j) { const int t = ord[j]; ord[j] = ord[j-1]; ord[j-1] = t; }
  for (int i = 0; i < MOE_FMT_COUNT; ++i) {
    const Best& e = b[ord[i]];
    if (e.us > 1e17) {
      if (!e.any_selected && moe_only())
        std::printf("  %-4s no row matched MOE_ONLY='%s'\n", moe_fmt_names[ord[i]], moe_only());
      else if (!e.any_selected)
        std::printf("  %-4s no legal row in this build/table\n", moe_fmt_names[ord[i]]);
      else
        std::printf("  %-4s selected row(s) did not run (launch rejected or D write witness failed)\n",
                    moe_fmt_names[ord[i]]);
      continue;
    }
    const double tf = 2.0 * double(bd.total) * double(bd.N) * double(bd.K) / (e.us * 1e-6) / 1e12;
    // "fastest" ONLY WHEN NOTHING TIES IT. With ties, naming a winner is the claim the samples do not support,
    // and it is the claim someone would otherwise carry into a tactic table and never revisit.
    const int nt = ties[ord[i]];
    // LAUNCH-BOUND IS SAID ON THE ROW, not left in the banner. A reader comparing two decode rows will not go
    // back and divide by the floor; the row has to carry it.
    // bench_floor is a HOST launch-rate measurement. The leader is selected on event span, but this diagnostic
    // must stay on the corresponding host wall or it would compare two clocks and recreate the protocol error.
    char const* lb = bench_floor::launch_bound(e.wall_us) ? "  [HOST-LAUNCH-BOUND]" : "";
    char verdict[96] = "";
    if (i == 0 && !moe_acu()) {
      if (reps < 2)      std::snprintf(verdict, sizeof verdict, "   <-- lowest (ONE pass: not a ranking)");
      else if (nt == 0)  std::snprintf(verdict, sizeof verdict, "   <-- fastest, separated");
      else               std::snprintf(verdict, sizeof verdict,
                                       "   <-- lowest median, but %d candidate(s) TIE it -- unresolved", nt);
    }
    // THE MASKED FRACTION IS ON THE ROW, because without it the MFU on the same row cannot be read. MFU's numerator
    // is 2*bd.total*N*K -- REAL rows -- while the kernel fetches and multiplies TM*mt of them. On a ragged band those
    // differ by ~2x, so a kernel running at 60% of the machine prints 30% here and reads as broken. The winning
    // tactic stays structured through selection; parsing "%dx" from a tag beginning with "i4 " made every old
    // summary silently print msk=0.
    const double msk = (e.has_tactic && e.tactic.tm > 0) ? masked_fraction(bd, e.tactic.tm) : 0.0;
    // ONE MFU, and it counts REAL work only. The numerator is 2*total*N*K -- what the model requires. Rows the
    // kernel padded out to TileM are the kernel's own overhead, not work, and they must count AGAINST it: an MFU
    // that forgave padding would be silent on exactly the defect it should expose (an oversized TileM at decode).
    // msk is printed beside it as a DIAGNOSTIC -- it says where the missing fraction went, it does not rescale it.
    if (moe_acu())
      std::printf("  %-4s %-30s %8.2f us ACU-cold-host-wall | NOT A PERFORMANCE NUMBER%s\n",
                  moe_fmt_names[ord[i]], e.tag, e.wall_us, verdict);
    else
      std::printf("  %-4s %-30s %8.3f us kernel-span-upper | host-wall %8.3f us |"
                  " %6.1f TF/s (%4.1f%% MFU) msk=%.0f%%%s%s\n",
                  moe_fmt_names[ord[i]], e.tag, e.us, e.wall_us,
                  tf, bench_measure::mfu_pct(tf), 100.0 * msk, lb, verdict);
    if (*lb && moe_verbose())
      std::printf("       %s host-wall is within 3x the host empty-launch floor (%.2f us)\n",
                  lb, bench_floor::us());
  }
  // THE TIES ARE THE OUTPUT, not a footnote. codex's H1/H2 pruning rules keep guards precisely so that a guard
  // landing inside the leader's band triggers expanding that stratum; without this list that rule has no input.
  if (reps > 1) {
    for (int i = 0; i < MOE_FMT_COUNT; ++i) {
      const Best& e = b[i];
      if (e.us > 1e17 || ties[i] == 0) continue;
      std::printf("  %-4s ties with the leader (expand these strata before calling anything a winner):\n",
                  moe_fmt_names[i]);
      double hi = 0;
      for (const auto& s : e.seen)
        if (std::strncmp(s.tag, e.tag, bench_measure::kTagBytes) == 0)
          hi = *std::max_element(s.us.begin(), s.us.end());
      for (const auto& s : e.seen) {
        if (std::strncmp(s.tag, e.tag, bench_measure::kTagBytes) == 0) continue;
        const double slo = *std::min_element(s.us.begin(), s.us.end());
        if (slo <= hi) std::printf("         %-30s median %8.2f  min %8.2f\n", s.tag, median_of(s.us), slo);
      }
    }
  }
  if (moe_verbose()) {
    std::printf("  distinct HBM%% is the compulsory lower bound: real A (total*K*2) + one read of each ACTIVE\n");
    std::printf("  expert's weights and scales + D. tile GB/s is the no-cache request model: A per n-tile and\n");
    std::printf("  weights/scales per m-tile. Its ratio to distinct names the required cache reuse; above peak means\n");
    std::printf("  the re-reads must be L2-served, not that DRAM exceeded 100%%. At decode, B and S are exact.\n");
    std::printf("  blk/wrp come from fold::warps_per_cu_chunked (registers billed to a power of two), NOT from a smem+warps\n");
    std::printf("  formula -- acu already showed that one to be register-limited and mis-ordering. wav = cta/(72*blk).\n");
    std::printf("  Then read mt and msk: smallest mt winning => the weight-bound rule holds; least msk => the dense\n");
    std::printf("  reasoning carries over; neither => the lever is occupancy and the next instrument is acu.\n");
    if (bd.Mmax == 1) {
      std::printf("\n  DECODE READING. Every active expert's weights and scales are read once (mt == active), so the B and S\n");
      std::printf("  terms are exact even though total traffic is still a lower bound. S%% is the scale channel's share\n");
      std::printf("  of that floor -- the ceiling on what #20 can buy before any reduction factor.\n");
    }
  }
  if (moe_only()) {
    bool any_selected = false;
    for (int i = 0; i < MOE_FMT_COUNT; ++i) any_selected = any_selected || b[i].any_selected;
    if (!any_selected) {
      std::printf("[lowbit-moe] ERROR: MOE_ONLY='%s' matched no compiled legal row\n", moe_only());
      return 3;
    }
  }
  return 0;
}
