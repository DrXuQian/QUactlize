#!/usr/bin/env python3
"""THE BENCH INVOCATIONS, DERIVED FROM THE MODELS -- not typed by hand.

The commands in .coord/BOX.md looked like

    "$BIN" 256 128 512 2048 32 2

which is `L Rows N K gs mode`. Six positional integers with no names, three of them derived (rows/expert from
the token count and the routing, N and K from the model and the tensor-parallel split), and nothing in the
command recording which model or which token count it stands for. Every one of those is a place to be silently
wrong, and a log of the output cannot be traced back to what was asked.

So the shapes come from benchmarks/workloads.py -- which holds the three target models as read off their
config.json, and derives the per-card projections under the standard TP split -- and this file turns them into
invocations. Nothing here transcribes a number.

    python3 benchmarks/fixtures.py                        # every model, every n-token, as a table
    python3 benchmarks/fixtures.py --emit moe             # runnable lines for the MoE bench
    python3 benchmarks/fixtures.py --emit dense           # runnable lines for the dense bench
    python3 benchmarks/fixtures.py --model Qwen3-32B      # one model

MoE always uses pinned router mode 4. Its second positional is TOKENS and the final one is top-k; the benchmark
derives the full expert histogram and Mmax. No command asserts rows/expert or shrinks L to fake decode.
"""
import argparse
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from benchmarks.workloads import MODELS, N_TOKENS, projections  # noqa: E402

# The k-quant the sweep is scoped to first (codex's L2: 025 asks about ONE stored schema, and other schemas are
# not legal interpretations of that tensor's bytes). gs comes from the format, not from a preference.
DEFAULT_GS = {"i4": 32}


def moe_case(cfg: dict, tokens: int):
    """-> (mode, tokens_arg, topk, note). Mmax is intentionally absent: the C++ router computes and prints it."""
    return 4, tokens, cfg["topk"], "pinned token-topk-hot16x4-wor-sm64-s44-v1; bench prints Mmax"


def fixtures(model: str, cfg: dict):
    """-> [(kind, label, n, k, tokens, extra)]. One entry per (projection, token count)."""
    out = []
    for name, n, k, split in projections(cfg):
        for t in N_TOKENS:
            if cfg["kind"] == "moe" and name.startswith("expert_"):
                mode, tokens_arg, topk, note = moe_case(cfg, t)
                out.append(("moe", f"{model}:{name}", n, k, t,
                            dict(experts=cfg["experts"], mode=mode, tokens=tokens_arg, topk=topk, note=note)))
            else:
                # Attention projections are dense even in an MoE model: every token goes through them.
                out.append(("dense", f"{model}:{name}", n, k, t, dict(note=f"m={t}")))
    return out


# The dense bench's option names, verified against its parser rather than remembered. lint_fixture_flags in
# ci/local_gates.py greps them out of the source, so renaming one there fails the gate instead of producing
# invocations that are silently ignored (cutlass' CommandLine does not complain about an unknown --flag).
DENSE_FLAGS = ("m", "n", "k", "g", "search_configs")


def dedup(rows):
    """Merge entries whose MEASUREMENT is identical -- same kind, shape and token count -- and say so in the
    label. expert_gate and expert_up have the same (n, k), so emitting both is running one benchmark twice; but
    DROPPING one silently would make the output look like the model has one FFN projection. The merged label
    names both."""
    out, seen = [], {}
    for kind, label, n, k, t, extra in rows:
        key = (kind, n, k, t, extra.get("mode"), extra.get("rows"))
        if key in seen:
            i = seen[key]
            prev = out[i]
            names = prev[1].split("+")
            proj = label.split(":", 1)[1]
            if proj not in [x.split(":", 1)[-1] for x in names]:
                out[i] = (prev[0], prev[1] + "+" + proj, *prev[2:])
            continue
        seen[key] = len(out)
        out.append((kind, label, n, k, t, extra))
    return out


def emit(kind: str, model_filter: str, gs: int):
    print("# GENERATED by benchmarks/fixtures.py -- shapes come from workloads.py, not from typing.")
    print("# Set BENCH_JSONL to collect samples; benchmarks/analyse.py decides the winner.")
    for model, cfg in MODELS.items():
        if model_filter and model_filter != model:
            continue
        rows = dedup([f for f in fixtures(model, cfg) if f[0] == kind])
        if not rows:
            continue
        print(f"\n# ===== {model}  ({cfg['kind']}, tp={cfg['tp']}) =====")
        for _, label, n, k, t, extra in rows:
            if kind == "moe":
                print(f'  "$BIN" {extra["experts"]} {extra["tokens"]} {n} {k} {gs} {extra["mode"]} {extra["topk"]}'
                      f'   # {label}  {extra["note"]}')
            else:
                print(f'  "$BIN" --m={t} --n={n} --k={k} --g={gs} --search_configs'
                      f'   # {label}  {extra["note"]}')


def table(model_filter: str):
    for model, cfg in MODELS.items():
        if model_filter and model_filter != model:
            continue
        print(f"\n== {model}  ({cfg['kind']}, tp={cfg['tp']}) ==")
        seen = set()
        for kind, label, n, k, t, extra in fixtures(model, cfg):
            key = (kind, n, k)
            if key in seen:
                continue
            seen.add(key)
            proj = label.split(":", 1)[1]
            print(f"   {kind:<6} {proj:<12} n={n:<6} k={k:<6}")
        if cfg["kind"] == "moe":
            print("   expert tokens -> pinned router invocation:")
            for t in N_TOKENS:
                mode, tokens_arg, topk, note = moe_case(cfg, t)
                print(f"      {t:<5} mode {mode}  tokens {tokens_arg:<4} top-k {topk}  {note}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--emit", choices=("moe", "dense"), help="print runnable invocations")
    ap.add_argument("--model", default="", help="restrict to one model name")
    ap.add_argument("--gs", type=int, default=DEFAULT_GS["i4"], help="group size (32 for Q4_K/Q5_K, 16 otherwise)")
    a = ap.parse_args()
    if a.model and a.model not in MODELS:
        ap.error(f"unknown model {a.model!r}; have {', '.join(MODELS)}")
    if a.emit:
        emit(a.emit, a.model, a.gs)
    else:
        table(a.model)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
