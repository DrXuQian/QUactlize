#!/usr/bin/env python3
"""Render the independently confirmed, Full-provider-only helper table."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import statistics

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / 'policies/dense_full_helpers_20261023.json'
HEADER = ROOT / 'quactlize/prefill/dense_full_helpers.inc'


def render(evidence):
    if (evidence['schema'] != 'quactlize.dense-full-helpers.v1' or
            evidence['device'] != dict(name='PPU-ZW810', compute_units=72) or
            evidence['m_values'] != [128, 256, 512, 1024, 2048] or
            len(evidence['rows']) != evidence['counts']['typed_points'] or
            len(evidence['rows']) != 350):
        raise ValueError('full helper evidence scope changed')
    rows = {}
    for r in evidence['rows']:
        key = tuple(r[x] for x in ('q', 'n', 'k', 'm', 'storage'))
        q, n, k, m, storage = key
        allowed = (0, 22, 23) if q in (8, 10, 11) else (0, 8, 20, 21)
        samples = r['confirmation_us']
        if (key in rows or q not in (8, 10, 11, 12, 13, 14) or n <= 0 or k <= 0 or
                n % 64 or k % 256 or m not in evidence['m_values'] or storage not in (0, 1) or
                r['dequant'] not in allowed or r['io'] not in range(4) or len(samples) != 2 or
                any(not math.isfinite(x) or x <= 0 for x in samples) or
                statistics.median(samples) != r['gpu_sum_us']):
            raise ValueError('invalid/duplicate full helper proof: ' + repr(key))
        rows[key] = r
    families = sorted({key[:3] for key in rows})
    if len(families) != 35:
        raise ValueError('full helper family inventory changed')
    result = ['// Generated by tools/generate_dense_full_helpers.py; do not hand-edit.',
              '// Full provider only: exact M/dtype, never TC/SF or a GEMM route selector.',
              '// Evidence SHA256: ' + hashlib.sha256(EVIDENCE.read_bytes()).hexdigest(),
              'static constexpr int dense_full_m[] = {128, 256, 512, 1024, 2048};',
              'struct DenseFullFamily { int q, n, k; DenseHelpers choices[2][5]; };',
              'static constexpr DenseFullFamily dense_full_families[] = {']
    for family in families:
        typed = []
        for storage in (0, 1):
            values = []
            for m in evidence['m_values']:
                r = rows[(*family, m, storage)]  # missing typed cell must fail generation
                values.append('{%d, %d}' % (r['dequant'], r['io']))
            typed.append('{' + ', '.join(values) + '}')
        result.append('    {%d, %d, %d, {%s}},' % (*family, ', '.join(typed)))
    return '\n'.join(result + ['};', ''])


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    text = render(json.loads(EVIDENCE.read_text()))
    if args.check:
        if HEADER.read_text() != text:
            raise SystemExit('stale dense full helper table')
        print('DENSE_FULL_HELPERS PASS typed_points=350 scope=FULL_ONLY')
    else:
        print(text, end='')
