#!/usr/bin/env python3
"""Port exactly the measured Q8 bodies, without changing their arithmetic."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from dev.gemv_simt.q8_address_source import body
from dev.strategy.refresh_selection import verify
from quactlize.execution.q8_refresh import EVIDENCE, TABLE, rows

# The experiment generators and Q8 kernel/activation headers were checked
# against the uploaded module receipts. Regeneration is not permission to
# re-admit a future, changed device body under the same timing evidence.
MEASURED_BODIES_SHA256 = '00d1eba87baa5e086dcc0a217583f3246ba73611a4c76048a74e4e7b5bcc138b'


def catalog():
    verify(json.loads(TABLE.read_text()))
    from dev.strategy.dense_m_selection import load
    dense = load()
    text = '// Generated by tools/generate_q8_refresh.py; exact dense/F32/F16/S1 only.\n'
    text += '// Evidence: '+EVIDENCE+'\n'
    text += '// Dense M evidence: '+dense['evidence_sha256']+'\n'
    for row in rows():
        q, mode, n, k, e, top, ch, m, compute = row['key']
        c, b = row['config'], row['implementation']['body']
        if (q, mode, e, top, ch, compute, c['variant'], c['values'], c['split']) != (
                8, 0, 1, 1, 1, 0, 5, 4, 1) or b not in (1, 3, 4, 5):
            raise ValueError('unmeasured Q8 launch scope')
        text += f'Q8R({n},{k},{m},{c["columns"]},{c["warps"]},{b})\n'
    return text


def header():
    bodies = [body(b) for b in (1, 3, 4, 5)]
    if hashlib.sha256(''.join(bodies).encode()).hexdigest() != MEASURED_BODIES_SHA256:
        raise ValueError('Q8 measured source body changed; new admission required')
    text = '''// Generated by tools/generate_q8_refresh.py from the measured address/window bodies.
// Keep the original Q8 header untouched: it remains the measured control.
#pragma once
#include "simt_q8_vector.cuh"
#include "simt_q8_refresh.hpp"

namespace quactlize::execution::simt::q8_refresh {
using namespace q8_vector;

__device__ __forceinline__ q4_s1::Row dense_locate(qkg_call_v1 const& c,unsigned row) {
    return {0,int64_t(row)*c.a_row_stride,int64_t(row)*c.out_row_stride};
}
'''
    for measured in bodies:
        text += measured.replace('general_locate<QKG_DENSE>', 'dense_locate')+'\n'
    for b, c, w in sorted({(r['implementation']['body'], r['config']['columns'],
                            r['config']['warps']) for r in rows()}):
        text += f'''__global__ void kernel_{b}_{c}_{w}(qkg_call_v1 c) {{
    address_body_{b}<1,0,1,{c},{w},4,true>(c,1);
}}
'''
    text += '''inline int launch(qkg_simt_call_v2 const& d,qkg_simt_config_v1 const& f) {
    int body=q8_refresh_body(d,f);
    if(!body) return QKG_INVALID;
    auto const& c=d.call;
    auto stream=static_cast<hggcStream_t>(c.stream);
    dim3 grid(c.n/(f.columns*f.values),c.rows);
'''
    for b, c, w in sorted({(r['implementation']['body'], r['config']['columns'],
                            r['config']['warps']) for r in rows()}):
        text += f'''    if(body=={b} && f.columns=={c} && f.warps=={w}) {{
        kernel_{b}_{c}_{w}<<<grid,{w}*32,0,stream>>>(c);
        return hggcGetLastError()==hggcSuccess ? QKG_OK : QKG_RUNTIME;
    }}
'''
    return text+'    return QKG_INVALID;\n}\n}\n'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    for name, text in [('q8_refresh.inc', catalog()), ('simt_q8_refresh.cuh', header())]:
        path = ROOT/'quactlize/execution'/name
        if a.check:
            if path.read_text() != text:
                raise ValueError('stale Q8 binding: '+str(path))
        else:
            path.write_text(text)


if __name__ == '__main__':
    main()
