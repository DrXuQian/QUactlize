#!/usr/bin/env python3
"""Audit uploaded confirmation evidence and emit the exact prefill selector."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from dev.strategy.prefill_review import review
from quactlize.runtime.tuning import digest
from tools.export_kpack_strategy import load_sources

EVIDENCE = ROOT / 'policies/kpack_prefill_confirmation_v1.json'
HEADER = ROOT / 'policies/kpack_prefill_confirmation_v1.hpp'


def header(evidence):
    configs, knots = {}, []
    for row in evidence['points']:
        w, r = row['workload'], row['recipe']; p = dict(r['parameters'])
        route = {'fq': 0, 'sf': 1, 'full': 2}[r['route']]
        ci = -1
        if r['kind'] == 'tc':
            mapping = 0x51344b5034540001 if w['qtype'] == 12 else 0x514b504b54000001
            values = [w['qtype'], route + (2 if w['operation'] == 'indexed' else 0)]
            values += [p[k] for k in ('tm', 'tn', 'tk', 'wm', 'wn', 'stages', 'ap', 'dn')]
            values += [p['persistent'], p['split'], p['grid_mode'], p['grid_b'], 0]
            text = '{"confirmed",' + json.dumps(p['symbol']) + ',"MEASURED",' + ','.join(map(str, values))
            text += ',UINT64_C(' + hex(mapping) + ')}'
            if text not in configs: configs[text] = len(configs)
            ci = configs[text]
        knots.append((w['qtype'], w['n'], w['k'], w['experts'], w['m'],
                      1 if w['compute'] == 'bf16' else 0, w['channels'], route,
                      p['dequant_config'], ci, row['gemm_us'], row['dequant_us']))
    lines = ['// Generated by tools/fit_prefill_confirmation.py; do not edit.', '#pragma once',
             '#include "kpack_zw810_runtime_v1.hpp"', 'namespace quactlize_prefill_confirmation_v1 {',
             'using Config = quactlize_kpack_runtime_v1::Config;',
             'inline constexpr char kEvidence[] = "' + digest(evidence) + '";',
             'struct Knot { int q,n,k,experts,tokens,compute,channels,route,dequant,config; double core_us,dequant_us; };',
             'inline constexpr Config kConfigs[] = {']
    lines += ['    ' + c + ',' for c in configs]
    lines += ['};', 'inline constexpr Knot kKnots[] = {']
    lines += ['    {' + ','.join(map(str, k)) + '},' for k in sorted(knots)]
    lines += ['};', '} // namespace quactlize_prefill_confirmation_v1', '']
    return '\n'.join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--archive', type=Path)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    if args.archive:
        evidence = review(args.archive, load_sources()[0])
    else:
        evidence = json.loads(EVIDENCE.read_text())
    text = json.dumps(evidence, sort_keys=True, separators=(',', ':')) + '\n'
    generated = header(evidence)
    if args.check:
        if EVIDENCE.read_text() != text or HEADER.read_text() != generated:
            raise ValueError('generated prefill selector differs from reviewed evidence')
    else:
        EVIDENCE.write_text(text); HEADER.write_text(generated)
    print('PREFILL_CONFIRMED ' + json.dumps(evidence['summary']))


if __name__ == '__main__':
    main()
