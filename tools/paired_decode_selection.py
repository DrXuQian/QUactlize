"""Validate and emit the measured paired gate/up recipe catalog."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / 'policies/kpack_gate_up_selection_v2.json'
OUTPUT = ROOT / 'quactlize/fusion/recipes.inc'
ARCHIVE_SHA = '8c6bc2c2daf1fa48f53b39ad71b4e75578c4c88aeffcfe8ee4a22385f2e2c082'
BASE_SOURCE = '0d7361eac2a3becdd53aa29b8b84d29cdc481fb8'
RECIPE_FIELDS = ('backend', 'split', 'tile_m', 'warps', 'reader', 'variant',
                 'columns', 'values', 'changes', 'hoist', 'fixed_n', 'fixed_k')
REQUEST_FIELDS = ('qtype', 'n', 'k', 'experts', 'tokens', 'mode', 'topk', 'channels',
                  'input_type', 'compute_type', 'output_type', 'round_projection',
                  'row_order', 'consumer', 'consumer_qtype', 'consumer_n')


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def validate(catalog):
    content = {k: v for k, v in catalog.items() if k != 'sha256'}
    if (catalog.get('schema') != 'quactlize.gate-up-selection.v2' or
        catalog.get('archive_sha256') != ARCHIVE_SHA or catalog.get('base_source') != BASE_SOURCE or
        catalog.get('sha256') != digest(content)):
        raise ValueError('paired catalog identity differs; recapture reviewed evidence')
    names = {r['name']: r for r in catalog['recipes']}
    if len(names) != len(catalog['recipes']) or len({r['id'] for r in names.values()}) != len(names):
        raise ValueError('duplicate paired implementation')
    for r in names.values():
        if r['id'] != digest({f: r[f] for f in RECIPE_FIELDS})[:16]:
            raise ValueError('paired recipe body differs')
    keys = set()
    for row in catalog['rows']:
        key = tuple(row['request'][f] for f in REQUEST_FIELDS)
        if key in keys or row['recipe'] not in names:
            raise ValueError('duplicate or unavailable paired choice')
        keys.add(key)
    return names


def header(catalog):
    names = validate(catalog)
    lines = ['// Generated by tools/generate_decode_selection.py. Do not edit.',
             '#ifdef QGU_CATALOG', 'QGU_CATALOG(0x' + catalog['sha256'][:16] + 'ULL)', '#endif',
             '#ifdef QGU_RECIPE', '// name,id,' + ','.join(RECIPE_FIELDS)]
    for r in catalog['recipes']:
        lines.append('QGU_RECIPE(' + r['name'] + ',0x' + r['id'] + 'ULL,' +
                     ','.join(str(r[f]) for f in RECIPE_FIELDS) + ')')
    lines += ['#endif', '#ifdef QGU_RULE', '// recipe,' + ','.join(REQUEST_FIELDS)]
    for row in catalog['rows']:
        lines.append('QGU_RULE(' + row['recipe'] + ',' +
                     ','.join(str(row['request'][f]) for f in REQUEST_FIELDS) + ')')
    lines += ['#endif', '#ifdef QGU_LEGACY', '// recipe,q,N,K,E,tokens,compute']
    for row in catalog['legacy']:
        lines.append('QGU_LEGACY(' + row['recipe'] + ',' +
                     ','.join(str(row[f]) for f in ('q', 'n', 'k', 'experts', 'tokens', 'compute')) + ')')
    lines += ['#endif', '#ifdef QGU_OVERRIDE', '// recipe,' + ','.join(REQUEST_FIELDS[:12])]
    for row in catalog['overrides']:
        lines.append('QGU_OVERRIDE(' + row['recipe'] + ',' +
                     ','.join(str(row['request'][f]) for f in REQUEST_FIELDS[:12]) + ')')
    return '\n'.join(lines + ['#endif', ''])
